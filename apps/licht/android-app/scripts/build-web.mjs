// Turns ../web into one self-contained HTML page for the app's WebView (src/web-html.js).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as esbuild from 'esbuild';

const here = dirname(fileURLToPath(import.meta.url));
const web = join(here, '..', '..', 'web');

const { outputFiles } = await esbuild.build({
  entryPoints: [join(web, 'app.js')],
  bundle: true,
  format: 'iife',
  target: 'chrome100',
  minify: true,
  write: false,
});
const script = outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const css = readFileSync(join(web, 'style.css'), 'utf8');
const icon = `data:image/svg+xml;base64,${readFileSync(join(web, 'icon.svg')).toString('base64')}`;

let html = readFileSync(join(web, 'index.html'), 'utf8')
  .replace('<link rel="icon" href="icon.svg" type="image/svg+xml">', `<link rel="icon" href="${icon}">`)
  .replace('<link rel="stylesheet" href="style.css">', `<style>${css}</style>`)
  .replace('<script type="module" src="app.js"></script>', '');
html = html.replace('</body>', `<script>${script}</script>\n</body>`);

writeFileSync(join(here, '..', 'src', 'web-html.js'), `// Generated by scripts/build-web.mjs – do not edit.\nexport default ${JSON.stringify(html)};\n`);
console.log(`web-html.js: ${(html.length / 1024).toFixed(0)} KB`);
