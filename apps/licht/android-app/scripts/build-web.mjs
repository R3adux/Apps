// Turns ../web into one self-contained HTML page for the app's WebView (src/web-html.js).
// Needs the packages of ../ (npm ci there first).
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildPage } from '../../scripts/build-page.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const html = await buildPage();
writeFileSync(join(here, '..', 'src', 'web-html.js'), `// Generated by scripts/build-web.mjs – do not edit.\nexport default ${JSON.stringify(html)};\n`);
console.log(`web-html.js: ${(html.length / 1024).toFixed(0)} KB`);
